// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the floor that the watchlist's own rule would keep: no token recorded, no
// wrapped, staked or bridged product of a token that trades, no versioned pool, no exchange. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, through four factors:
//
//   category multiple = the median market-cap-to-TVL ratio of the snapshot's live-token protocols in
//                         the same category (at least 3 of them, market cap and TVL both positive,
//                         exchanges excluded); a category with fewer than 3 live protocols uses the
//                         global median over all live protocols. Clamped to [0.05, 0.75], so one wild
//                         outlier cannot set the multiple for a whole category.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.05 x min(chains - 1, 4)            (more chains, broader distribution)
//   implied    = max(1, round(tvl_usd x categoryMultiple x growthMult x maturity x breadth))
//
// The starter's flat 0.25 multiple is replaced by the comparables the snapshot itself carries: a
// lending protocol is not priced like a DEX, and a category with no live peers is priced on the whole
// market's median instead of a guess. No protocol name is ever special-cased: the same function scores
// every row, and the dashboard prints the calibration table the function used.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
